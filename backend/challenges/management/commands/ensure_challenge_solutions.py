import json

from django.core.management.base import BaseCommand

from ai_assistant.service import MultiAgentChatService
from challenges.models import Challenge, ChallengeSolution


class Command(BaseCommand):
    help = 'Ensure every active challenge has a non-flag solution walkthrough.'

    def add_arguments(self, parser):
        parser.add_argument(
            '--overwrite-generated',
            action='store_true',
            help='Refresh solutions previously generated by this command.',
        )

    def handle(self, *args, **options):
        service = MultiAgentChatService()
        overwrite_generated = options.get('overwrite_generated', False)
        challenges = Challenge.objects.filter(is_active=True).select_related('category').order_by('id')

        created = 0
        updated = 0
        skipped = 0

        for challenge in challenges:
            challenge_info = {
                'id': challenge.id,
                'title': challenge.title,
                'category': challenge.category.name if challenge.category else '',
                'category_name': challenge.category.name if challenge.category else '',
                'difficulty': challenge.difficulty,
                'description': challenge.description,
                'hint': challenge.hint,
            }
            solution_guide = service._build_challenge_solution_guide(challenge_info)
            content = self._build_solution_content(challenge, solution_guide)
            hint_map = self._build_hint_map(challenge, solution_guide)

            existing = getattr(challenge, 'solution', None)
            if existing:
                generated = 'generated_by=ensure_challenge_solutions' in (existing.hint_map or '')
                if overwrite_generated and generated:
                    existing.answer_type = 'step'
                    existing.content = content
                    existing.hint_map = json.dumps(hint_map, ensure_ascii=False, indent=2)
                    existing.is_enabled = True
                    existing.save(update_fields=['answer_type', 'content', 'hint_map', 'is_enabled', 'updated_at'])
                    updated += 1
                else:
                    skipped += 1
                continue

            ChallengeSolution.objects.create(
                challenge=challenge,
                answer_type='step',
                content=content,
                hint_map=json.dumps(hint_map, ensure_ascii=False, indent=2),
                is_enabled=True,
            )
            created += 1

        self.stdout.write(self.style.SUCCESS(
            f'Challenge solutions ensured: created={created}, updated={updated}, skipped={skipped}.'
        ))

    def _build_solution_content(self, challenge, solution_guide: str) -> str:
        category = challenge.category.name if challenge.category else '未分类'
        return '\n'.join([
            f'【{challenge.title}】标准解题思路',
            '',
            '说明：这是一份用于学习和讲解的解题思路，不包含 flag，也不硬编码最终提交值。',
            '',
            '## 题目信息',
            f'- 题号：{challenge.id}',
            f'- 分类：{category}',
            f'- 难度：{challenge.difficulty}',
            f'- 分值：{challenge.score}',
            f'- 题面：{challenge.description or "无"}',
            f'- 提示：{challenge.hint or "无"}',
            '',
            solution_guide,
            '',
            '## 推荐回答方式',
            '1. 先给出题面目标和关键知识点。',
            '2. 再按验证顺序说明每一步为什么要做、观察什么现象。',
            '3. 给出可复现的命令、脚本结构或 payload 构造思路，但不直接给 flag。',
            '4. 最后补充常见失败原因、防护建议和同类题迁移方法。',
        ])

    def _build_hint_map(self, challenge, solution_guide: str) -> dict:
        return {
            'generated_by': 'ensure_challenge_solutions',
            'default': (
                f'{challenge.title} 的解题思路应先围绕题面关键词定位知识点，'
                '再用最小实验验证入口和现象，最后整理可复现步骤。'
            ),
            '思路': solution_guide,
            '步骤': solution_guide,
            '解析': solution_guide,
            '答案': '本题答案记录只提供解题思路，不提供 flag。请根据解析步骤自行验证并提交。',
            'flag': '不直接提供 flag。建议按解题思路完成验证后自行提交结果。',
        }
